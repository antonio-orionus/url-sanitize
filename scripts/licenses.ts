/**
 * Derive every license label and license-text copy from the catalogs' own
 * `sources[].license`, so a source's license is stated once: in its sync
 * script, which writes it into the source's metadata.
 *
 * Writes (all checked by CI's stale-generated-files step):
 *   catalog/licenses.json               — data licenses of the default catalog
 *   NOTICE                              — what the native binary embeds
 *   crates/url-sanitize/{LICENSE,NOTICE,LICENSES/}, its Cargo.toml `license`
 *   packages/<source>/LICENSES/, their package.json `license`
 *   Formula/url-sanitize.rb and bucket/url-sanitize.json `license`
 *
 * The release workflows and scripts/render-package-manager-files.mjs read
 * catalog/licenses.json.
 */
import { copyFile, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import type { SanitizerCatalog } from '@url-sanitize/core';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const at = (...parts: string[]): string => resolve(root, ...parts);

/** How NOTICE names each source. A new source must be added here. */
const SOURCE_NAMES: Record<string, string> = {
  clearurls: 'ClearURLs Rules (https://github.com/ClearURLs/Rules)',
  adguard: 'AdGuard URL Tracking filter (https://github.com/AdguardTeam/AdguardFilters)',
  brave:
    'Brave Debouncer, query-filter and clean-URLs lists (https://github.com/brave/adblock-lists)',
  firefox: 'Firefox Query Stripping records (Mozilla Remote Settings)'
};

export interface LicenseInputs {
  /** The default catalog, embedded in the native binary. */
  defaultCatalog: SanitizerCatalog;
  /** Each source package's own catalog, keyed by package directory. */
  sourcePackages: Record<string, SanitizerCatalog>;
}

function dataLicenses(catalog: SanitizerCatalog): string[] {
  const licenses = new Set<string>();
  for (const source of catalog.sources) {
    if (!source.license) throw new Error(`source ${source.name} has no license`);
    licenses.add(source.license);
  }
  return [...licenses].sort();
}

/** Make `dir` hold exactly the texts of `licenses`, copied from the root LICENSES/. */
async function syncLicenseTexts(dir: string, licenses: string[]): Promise<void> {
  await mkdir(dir, { recursive: true });
  const wanted = new Set(licenses.map((id) => `${id}.txt`));
  for (const name of await readdir(dir)) {
    if (!wanted.has(name)) await rm(resolve(dir, name));
  }
  for (const name of wanted) await copyFile(at('LICENSES', name), resolve(dir, name));
}

async function rewrite(path: string, edit: (text: string) => string): Promise<void> {
  const before = await readFile(path, 'utf8');
  const after = edit(before);
  if (after === before) return;
  await writeFile(path, after);
}

function replaceOnce(text: string, pattern: RegExp, replacement: string, path: string): string {
  if (!pattern.test(text)) throw new Error(`${path}: no match for ${pattern}`);
  return text.replace(pattern, replacement);
}

function renderNotice(catalog: SanitizerCatalog, expression: string): string {
  const lines = catalog.sources.map((source) => {
    const name = SOURCE_NAMES[source.name];
    if (!name) throw new Error(`add ${source.name} to SOURCE_NAMES in scripts/licenses.ts`);
    return `- ${name}: ${source.license}`;
  });
  return `url-sanitize: code is MIT (see LICENSE). Rule data from upstream lists keeps
its source license.

The native \`url-sanitize\` binary (crates.io, GitHub Releases, Homebrew, Scoop)
embeds the default catalog, built from:

${lines.join('\n')}

So the binary as distributed is ${expression}.
The license texts are in LICENSES/.

Corresponding source: every release is built from the git tag that matches
\`url-sanitize --version\`, https://github.com/antonio-orionus/url-sanitize/tree/v<version>,
and the same source is published as the \`url-sanitize\` crate on crates.io.
The embedded data is crates/url-sanitize/catalog/catalog.json. To use modified
rule data, replace that file and run \`cargo build --release -p url-sanitize\`.

The AdGuard URL Tracking filter (GPL-3.0, via @url-sanitize/adguard) is not
part of the default catalog or the binary.

This project is not affiliated with or endorsed by ClearURLs, Brave, Mozilla,
or AdGuard.

This file is generated by scripts/licenses.ts (pnpm build:catalog).
`;
}

export async function writeLicenseArtifacts({
  defaultCatalog,
  sourcePackages
}: LicenseInputs): Promise<void> {
  // Source packages: MIT code plus their one data license.
  for (const [dir, catalog] of Object.entries(sourcePackages)) {
    const licenses = dataLicenses(catalog);
    await syncLicenseTexts(at('packages', dir, 'LICENSES'), licenses);
    const manifestPath = at('packages', dir, 'package.json');
    const manifest = JSON.parse(await readFile(manifestPath, 'utf8')) as { license?: string };
    manifest.license = ['MIT', ...licenses].join(' AND ');
    await rewrite(manifestPath, () => `${JSON.stringify(manifest, null, 2)}\n`);
  }

  // The native binary: MIT code plus every data license of the default catalog.
  const licenses = dataLicenses(defaultCatalog);
  const expression = ['MIT', ...licenses].join(' AND ');
  await writeFile(
    at('catalog', 'licenses.json'),
    `${JSON.stringify({ binary: expression, dataLicenses: licenses }, null, 2)}\n`
  );
  await writeFile(at('NOTICE'), renderNotice(defaultCatalog, expression));

  const crate = at('crates', 'url-sanitize');
  await copyFile(at('LICENSE'), resolve(crate, 'LICENSE'));
  await copyFile(at('NOTICE'), resolve(crate, 'NOTICE'));
  await syncLicenseTexts(resolve(crate, 'LICENSES'), licenses);
  const cargoPath = resolve(crate, 'Cargo.toml');
  await rewrite(cargoPath, (text) =>
    replaceOnce(text, /^license = ".*"$/m, `license = "${expression}"`, cargoPath)
  );

  const formulaPath = at('Formula', 'url-sanitize.rb');
  const homebrew = `license all_of: [${['MIT', ...licenses].map((id) => `"${id}"`).join(', ')}]`;
  await rewrite(formulaPath, (text) =>
    replaceOnce(text, /^ {2}license .*$/m, `  ${homebrew}`, formulaPath)
  );

  const bucketPath = at('bucket', 'url-sanitize.json');
  const bucket = JSON.parse(await readFile(bucketPath, 'utf8')) as {
    license?: { identifier: string; url: string };
  };
  // Scoop separates licenses that all apply with a comma.
  bucket.license = {
    identifier: ['MIT', ...licenses].join(','),
    url: 'https://github.com/antonio-orionus/url-sanitize/blob/main/NOTICE'
  };
  await rewrite(bucketPath, () => `${JSON.stringify(bucket, null, 2)}\n`);

  console.log(`binary license: ${expression}`);
}
